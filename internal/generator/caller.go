package generator

import (
	"fmt"
	"strings"

	"github.com/cicd-automate/cicd-automate/internal/model"
)

const generatedBanner = "# Generated by cicd-automate — run `cicd sync` to update.\n"

// RenderReusableCI generates a thin caller .github/workflows/ci.yml referencing reusable workflows.
func RenderReusableCI(m model.Manifest, src model.SourceRef, local bool) string {
	var b strings.Builder
	b.WriteString(generatedBanner)
	b.WriteString("name: CI\n\n")
	b.WriteString("on:\n")
	b.WriteString("  push:\n")
	fmt.Fprintf(&b, "    branches: [%s]\n", m.DefaultBranch)
	b.WriteString("  pull_request:\n")
	b.WriteString("  workflow_dispatch:\n\n")
	b.WriteString("concurrency:\n")
	b.WriteString("  group: ${{ github.workflow }}-${{ github.ref }}\n")
	b.WriteString("  cancel-in-progress: true\n\n")
	b.WriteString("permissions:\n")
	b.WriteString("  contents: read\n\n")
	b.WriteString("jobs:\n")

	usePathFilter := shouldUsePathFilter(m.Stacks)
	if usePathFilter {
		writePathFilterJob(&b, m.Stacks)
	}

	for _, stack := range m.Stacks {
		jobID := sanitizeJobID(stack.Name)
		wfFile := reusableFileForStack(stack.Type)
		fmt.Fprintf(&b, "  %s:\n", jobID)
		if usePathFilter {
			fmt.Fprintf(&b, "    needs: changes\n")
			fmt.Fprintf(&b, "    if: github.event_name != 'pull_request' || needs.changes.outputs.%s == 'true'\n", jobID)
		}
		fmt.Fprintf(&b, "    uses: %s\n", src.WorkflowUses(wfFile, local))
		b.WriteString("    with:\n")
		writeReusableStackInputs(&b, stack)
		b.WriteString("\n")
	}

	return strings.TrimRight(b.String(), "\n") + "\n"
}

func shouldUsePathFilter(stacks []model.StackConfig) bool {
	if len(stacks) <= 1 {
		return false
	}
	subCount := 0
	for _, s := range stacks {
		if s.Directory != "" && s.Directory != "." {
			subCount++
		}
	}
	return subCount > 0
}

func writePathFilterJob(b *strings.Builder, stacks []model.StackConfig) {
	b.WriteString("  changes:\n")
	b.WriteString("    name: Detect Changed Services\n")
	b.WriteString("    runs-on: ubuntu-latest\n")
	b.WriteString("    outputs:\n")
	for _, s := range stacks {
		id := sanitizeJobID(s.Name)
		fmt.Fprintf(b, "      %s: ${{ steps.filter.outputs.%s }}\n", id, id)
	}
	b.WriteString("    steps:\n")
	b.WriteString("      - name: Checkout repository\n")
	b.WriteString("        uses: actions/checkout@v4\n")
	b.WriteString("      - name: Check path filters\n")
	b.WriteString("        id: filter\n")
	b.WriteString("        uses: dorny/paths-filter@v3\n")
	b.WriteString("        with:\n")
	b.WriteString("          filters: |\n")
	for _, s := range stacks {
		id := sanitizeJobID(s.Name)
		fmt.Fprintf(b, "            %s:\n", id)
		if s.Directory == "" || s.Directory == "." {
			b.WriteString("              - '**'\n")
		} else {
			dir := strings.TrimSuffix(s.Directory, "/")
			fmt.Fprintf(b, "              - '%s/**'\n", dir)
		}
	}
	b.WriteString("\n")
}

func reusableFileForStack(st model.StackType) string {
	switch st {
	case model.StackNode:
		return "reusable-node.yml"
	case model.StackPython:
		return "reusable-python.yml"
	case model.StackGo:
		return "reusable-go.yml"
	case model.StackRust:
		return "reusable-rust.yml"
	default:
		return "reusable-generic.yml"
	}
}

func writeReusableStackInputs(b *strings.Builder, s model.StackConfig) {
	dir := s.Directory
	if dir == "" {
		dir = "."
	}
	fmt.Fprintf(b, "      working-directory: %q\n", dir)

	switch s.Type {
	case model.StackNode:
		pm := s.PackageManager
		if pm == "" {
			pm = "npm"
		}
		fmt.Fprintf(b, "      package-manager: %q\n", pm)
		if s.VersionFile != "" {
			fmt.Fprintf(b, "      node-version-file: %q\n", s.VersionFile)
		} else if s.RuntimeVersion != "" {
			fmt.Fprintf(b, "      node-version: %q\n", s.RuntimeVersion)
		}
		fmt.Fprintf(b, "      run-lint: %t\n", s.RunLint)
		if s.LintCommand != "" {
			fmt.Fprintf(b, "      lint-command: %q\n", s.LintCommand)
		}
		fmt.Fprintf(b, "      run-typecheck: %t\n", s.RunTypecheck)
		if s.TypecheckCmd != "" {
			fmt.Fprintf(b, "      typecheck-command: %q\n", s.TypecheckCmd)
		}
		fmt.Fprintf(b, "      run-test: %t\n", s.RunTest)
		if s.TestCommand != "" {
			fmt.Fprintf(b, "      test-command: %q\n", s.TestCommand)
		}
		fmt.Fprintf(b, "      run-build: %t\n", s.RunBuild)
		if s.BuildCommand != "" {
			fmt.Fprintf(b, "      build-command: %q\n", s.BuildCommand)
		}
		if s.UploadCoverage {
			b.WriteString("      upload-coverage: true\n")
		}

	case model.StackPython:
		pm := s.PackageManager
		if pm == "" {
			pm = "uv"
		}
		fmt.Fprintf(b, "      package-manager: %q\n", pm)
		if s.VersionFile != "" {
			fmt.Fprintf(b, "      python-version-file: %q\n", s.VersionFile)
		} else if s.RuntimeVersion != "" {
			fmt.Fprintf(b, "      python-version: %q\n", s.RuntimeVersion)
		}
		fmt.Fprintf(b, "      run-lint: %t\n", s.RunLint)
		if s.LintCommand != "" {
			fmt.Fprintf(b, "      lint-command: %q\n", s.LintCommand)
		}
		fmt.Fprintf(b, "      run-format-check: %t\n", s.RunFormatCheck)
		if s.FormatCommand != "" {
			fmt.Fprintf(b, "      format-command: %q\n", s.FormatCommand)
		}
		fmt.Fprintf(b, "      run-typecheck: %t\n", s.RunTypecheck)
		if s.TypecheckCmd != "" {
			fmt.Fprintf(b, "      typecheck-command: %q\n", s.TypecheckCmd)
		}
		fmt.Fprintf(b, "      run-test: %t\n", s.RunTest)
		if s.TestCommand != "" {
			fmt.Fprintf(b, "      test-command: %q\n", s.TestCommand)
		}
		if s.UploadCoverage {
			b.WriteString("      upload-coverage: true\n")
		}

	case model.StackGo:
		if s.VersionFile != "" {
			fmt.Fprintf(b, "      go-version-file: %q\n", s.VersionFile)
		} else if s.RuntimeVersion != "" {
			fmt.Fprintf(b, "      go-version: %q\n", s.RuntimeVersion)
		}
		fmt.Fprintf(b, "      run-vet: true\n")
		fmt.Fprintf(b, "      run-lint: %t\n", s.RunLint)
		fmt.Fprintf(b, "      run-test: %t\n", s.RunTest)
		fmt.Fprintf(b, "      run-build: %t\n", s.RunBuild)
		if s.BuildCommand != "" {
			fmt.Fprintf(b, "      build-command: %q\n", s.BuildCommand)
		}
		if s.UploadCoverage {
			b.WriteString("      upload-coverage: true\n")
		}

	case model.StackRust:
		if s.RuntimeVersion != "" {
			fmt.Fprintf(b, "      toolchain: %q\n", s.RuntimeVersion)
		}
		fmt.Fprintf(b, "      run-fmt: %t\n", s.RunFormatCheck)
		fmt.Fprintf(b, "      run-clippy: %t\n", s.RunLint)
		fmt.Fprintf(b, "      run-test: %t\n", s.RunTest)
		fmt.Fprintf(b, "      run-build: %t\n", s.RunBuild)

	default:
		if s.SetupCommand != "" {
			fmt.Fprintf(b, "      setup-command: %q\n", s.SetupCommand)
		}
		if s.LintCommand != "" {
			fmt.Fprintf(b, "      lint-command: %q\n", s.LintCommand)
		}
		if s.TestCommand != "" {
			fmt.Fprintf(b, "      test-command: %q\n", s.TestCommand)
		}
		if s.BuildCommand != "" {
			fmt.Fprintf(b, "      build-command: %q\n", s.BuildCommand)
		}
	}
}

// RenderReusableDocker generates a thin caller .github/workflows/docker.yml.
func RenderReusableDocker(m model.Manifest, src model.SourceRef, local bool) string {
	d := m.Docker
	ctx := d.Context
	if ctx == "" {
		ctx = "."
	}
	df := d.Dockerfile
	if df == "" {
		df = "Dockerfile"
	}
	reg := d.Registry
	if reg == "" {
		reg = "ghcr.io"
	}
	platforms := d.Platforms
	if platforms == "" {
		platforms = "linux/amd64,linux/arm64"
	}

	var b strings.Builder
	b.WriteString(generatedBanner)
	b.WriteString("name: Docker\n\n")
	b.WriteString("on:\n")
	b.WriteString("  push:\n")
	fmt.Fprintf(&b, "    branches: [%s]\n", m.DefaultBranch)
	b.WriteString("    tags: ['v*']\n")
	b.WriteString("  pull_request:\n")
	b.WriteString("  workflow_dispatch:\n\n")
	b.WriteString("permissions:\n")
	b.WriteString("  contents: read\n")
	b.WriteString("  packages: write\n")
	b.WriteString("  security-events: write\n\n")
	b.WriteString("jobs:\n")
	b.WriteString("  docker:\n")
	fmt.Fprintf(&b, "    uses: %s\n", src.WorkflowUses("reusable-docker.yml", local))
	b.WriteString("    with:\n")
	fmt.Fprintf(&b, "      context: %q\n", ctx)
	fmt.Fprintf(&b, "      dockerfile: %q\n", df)
	fmt.Fprintf(&b, "      registry: %q\n", reg)
	if d.ImageName != "" {
		fmt.Fprintf(&b, "      image-name: %q\n", d.ImageName)
	}
	fmt.Fprintf(&b, "      platforms: %q\n", platforms)
	b.WriteString("      push: ${{ github.event_name != 'pull_request' }}\n")
	fmt.Fprintf(&b, "      scan-trivy: %t\n", d.ScanTrivy)
	if reg != "ghcr.io" {
		b.WriteString("    secrets:\n")
		b.WriteString("      REGISTRY_USERNAME: ${{ secrets.REGISTRY_USERNAME }}\n")
		b.WriteString("      REGISTRY_PASSWORD: ${{ secrets.REGISTRY_PASSWORD }}\n")
	}
	return b.String()
}

// RenderReusableDeploy generates a thin caller .github/workflows/deploy.yml.
func RenderReusableDeploy(m model.Manifest, src model.SourceRef, local bool) string {
	dep := m.Deploy
	envName := dep.Environment
	if envName == "" {
		envName = "production"
	}
	dir := dep.Directory
	if dir == "" {
		dir = "."
	}

	var b strings.Builder
	b.WriteString(generatedBanner)
	b.WriteString("name: Deploy\n\n")
	b.WriteString("on:\n")
	b.WriteString("  push:\n")
	fmt.Fprintf(&b, "    branches: [%s]\n", m.DefaultBranch)
	b.WriteString("  workflow_dispatch:\n\n")
	b.WriteString("concurrency:\n")
	fmt.Fprintf(&b, "  group: deploy-%s\n", envName)
	b.WriteString("  cancel-in-progress: false\n\n")
	b.WriteString("permissions:\n")
	b.WriteString("  contents: read\n")
	b.WriteString("  id-token: write\n\n")
	b.WriteString("jobs:\n")
	b.WriteString("  deploy:\n")
	fmt.Fprintf(&b, "    uses: %s\n", src.WorkflowUses("reusable-deploy.yml", local))
	b.WriteString("    with:\n")
	fmt.Fprintf(&b, "      provider: %q\n", dep.Provider)
	fmt.Fprintf(&b, "      environment: %q\n", envName)
	fmt.Fprintf(&b, "      working-directory: %q\n", dir)
	if dep.ProjectName != "" {
		fmt.Fprintf(&b, "      project-name: %q\n", dep.ProjectName)
	}
	if dep.DistDir != "" && (dep.Provider == "cloudflare-pages" || dep.Provider == "aws-s3") {
		fmt.Fprintf(&b, "      dist-dir: %q\n", dep.DistDir)
	}
	if dep.AWSRegion != "" && dep.Provider == "aws-s3" {
		fmt.Fprintf(&b, "      aws-region: %q\n", dep.AWSRegion)
	}
	if dep.S3Bucket != "" && dep.Provider == "aws-s3" {
		fmt.Fprintf(&b, "      s3-bucket: %q\n", dep.S3Bucket)
	}
	if dep.BuildCommand != "" {
		fmt.Fprintf(&b, "      build-command: %q\n", dep.BuildCommand)
	}
	if dep.DeployCommand != "" && dep.Provider == "custom" {
		fmt.Fprintf(&b, "      deploy-command: %q\n", dep.DeployCommand)
	}

	secrets := deploySecretsForProvider(dep.Provider)
	if len(secrets) > 0 {
		b.WriteString("    secrets:\n")
		for _, sec := range secrets {
			fmt.Fprintf(&b, "      %s: ${{ secrets.%s }}\n", sec, sec)
		}
	}
	return b.String()
}

func deploySecretsForProvider(provider string) []string {
	switch provider {
	case "vercel":
		return []string{"VERCEL_TOKEN", "VERCEL_ORG_ID", "VERCEL_PROJECT_ID"}
	case "fly":
		return []string{"FLY_API_TOKEN"}
	case "cloudflare-pages", "cloudflare-workers":
		return []string{"CLOUDFLARE_API_TOKEN", "CLOUDFLARE_ACCOUNT_ID"}
	case "aws-s3":
		return []string{"AWS_ROLE_ARN"}
	case "custom":
		return []string{"DEPLOY_TOKEN"}
	default:
		return nil
	}
}

// RenderReusableRelease generates a thin caller .github/workflows/release.yml.
func RenderReusableRelease(m model.Manifest, src model.SourceRef, local bool) string {
	rel := m.Release
	strategy := rel.Strategy
	if strategy == "" {
		strategy = "release-please"
	}
	relType := rel.ReleaseType
	if relType == "" {
		relType = inferReleaseType(m.Stacks)
	}

	var b strings.Builder
	b.WriteString(generatedBanner)
	b.WriteString("name: Release\n\n")
	b.WriteString("on:\n")
	if strategy == "release-please" {
		b.WriteString("  push:\n")
		fmt.Fprintf(&b, "    branches: [%s]\n", m.DefaultBranch)
	} else {
		b.WriteString("  push:\n")
		b.WriteString("    tags: ['v*']\n")
	}
	b.WriteString("  workflow_dispatch:\n\n")
	b.WriteString("permissions:\n")
	b.WriteString("  contents: write\n")
	b.WriteString("  pull-requests: write\n\n")
	b.WriteString("jobs:\n")
	b.WriteString("  release:\n")
	fmt.Fprintf(&b, "    uses: %s\n", src.WorkflowUses("reusable-release.yml", local))
	b.WriteString("    with:\n")
	fmt.Fprintf(&b, "      strategy: %q\n", strategy)
	if strategy == "release-please" {
		fmt.Fprintf(&b, "      release-type: %q\n", relType)
	}
	return b.String()
}

func inferReleaseType(stacks []model.StackConfig) string {
	if len(stacks) == 1 {
		switch stacks[0].Type {
		case model.StackNode:
			return "node"
		case model.StackPython:
			return "python"
		case model.StackGo:
			return "go"
		case model.StackRust:
			return "rust"
		}
	}
	return "simple"
}

func sanitizeJobID(name string) string {
	if name == "" {
		return "ci"
	}
	var out strings.Builder
	for i, r := range name {
		isAlpha := (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z')
		isDigit := r >= '0' && r <= '9'
		if isAlpha || (i > 0 && (isDigit || r == '_' || r == '-')) {
			out.WriteRune(r)
		} else if i == 0 {
			out.WriteRune('j')
		} else {
			out.WriteRune('-')
		}
	}
	return strings.ToLower(out.String())
}
